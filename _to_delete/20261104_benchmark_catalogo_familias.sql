INSERT INTO benchmark.benchmark_productos
    (codigo, nombre_producto, categoria, precio_referencia, estado, id_familia)
SELECT c.codigo, c.nombre_producto, c.categoria, c.precio_referencia, 1, f.id
FROM catalogo c
JOIN benchmark.benchmark_familias f ON lower(f.nombre) = lower(c.familia)
ON CONFLICT (codigo) DO UPDATE SET
    id_familia          = EXCLUDED.id_familia,
    estado              = 1,
    nombre_producto     = EXCLUDED.nombre_producto,
    categoria           = EXCLUDED.categoria,
    precio_referencia   = EXCLUDED.precio_referencia,
    fecha_actualizacion = CURRENT_TIMESTAMP;

-- Verificación: debe devolver 91 productos repartidos por familia
SELECT f.nombre AS familia, count(*) AS productos
FROM benchmark.benchmark_productos p
JOIN benchmark.benchmark_familias f ON f.id = p.id_familia
WHERE p.estado = 1
GROUP BY f.nombre, f.orden ORDER BY f.orden;
