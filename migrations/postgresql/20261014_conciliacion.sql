CREATE TABLE IF NOT EXISTS conciliacion_vinculos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 deposito_id BIGINT NOT NULL REFERENCES depositos(id),
 movimiento_id BIGINT NOT NULL REFERENCES transacciones_estado_cuenta(id),
 estado VARCHAR(20) NOT NULL CHECK (estado IN ('PREVALIDADO','APROBADO','DEVUELTO','CERRADO')),
 huella CHAR(64) NOT NULL,
 observacion TEXT NOT NULL,
 creado_por BIGINT NOT NULL REFERENCES usuarios(id),
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 revisado_por BIGINT REFERENCES usuarios(id),
 revisado_en TIMESTAMP,
 motivo TEXT,
 CHECK (revisado_por IS NULL OR revisado_por <> creado_por)
);
CREATE UNIQUE INDEX IF NOT EXISTS conciliacion_deposito_activo ON conciliacion_vinculos(deposito_id) WHERE estado <> 'DEVUELTO';
CREATE UNIQUE INDEX IF NOT EXISTS conciliacion_movimiento_activo ON conciliacion_vinculos(movimiento_id) WHERE estado <> 'DEVUELTO';
CREATE TABLE IF NOT EXISTS conciliacion_partidas (
 movimiento_id BIGINT PRIMARY KEY REFERENCES transacciones_estado_cuenta(id),
 motivo TEXT NOT NULL,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 huella CHAR(64) NOT NULL
);
CREATE TABLE IF NOT EXISTS conciliacion_cierres (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 estado_cuenta_id BIGINT NOT NULL UNIQUE REFERENCES estados_cuenta(id),
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 resumen JSONB NOT NULL
);
