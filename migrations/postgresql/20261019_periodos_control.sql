CREATE TABLE IF NOT EXISTS conciliacion_control (
 id SMALLINT PRIMARY KEY CHECK(id=1), propietario_id BIGINT NOT NULL REFERENCES usuarios(id)
);
INSERT INTO conciliacion_control(id,propietario_id)
 SELECT 1,id FROM usuarios WHERE estado=1 AND id_rol=5 ORDER BY id LIMIT 1 ON CONFLICT(id) DO NOTHING;
CREATE TABLE IF NOT EXISTS conciliacion_periodos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 mes DATE NOT NULL UNIQUE CHECK(EXTRACT(DAY FROM mes)=1),
 estado VARCHAR(12) NOT NULL CHECK(estado IN ('ABIERTO','BLOQUEADO','CERRADO')),
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id), actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS conciliacion_un_mes_abierto ON conciliacion_periodos(estado) WHERE estado='ABIERTO';
INSERT INTO conciliacion_periodos(mes,estado,usuario_id)
 SELECT DATE_TRUNC('month',CURRENT_DATE)::date,'ABIERTO',propietario_id FROM conciliacion_control
 WHERE NOT EXISTS(SELECT 1 FROM conciliacion_periodos) ON CONFLICT(mes) DO NOTHING;
CREATE TABLE IF NOT EXISTS conciliacion_autorizaciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id), periodo_id BIGINT NOT NULL REFERENCES conciliacion_periodos(id),
 estado_cuenta_id BIGINT NOT NULL REFERENCES estados_cuenta(id), otorgado_por BIGINT NOT NULL REFERENCES usuarios(id),
 vence_en TIMESTAMPTZ NOT NULL, motivo TEXT NOT NULL, revocado BOOLEAN NOT NULL DEFAULT FALSE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS conciliacion_ajustes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 estado_cuenta_id BIGINT NOT NULL REFERENCES estados_cuenta(id), periodo_id BIGINT NOT NULL REFERENCES conciliacion_periodos(id),
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id), fecha DATE NOT NULL,
 importe NUMERIC(15,2) NOT NULL CHECK(importe<>0), documento VARCHAR(200) NOT NULL, motivo TEXT NOT NULL,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS conciliacion_control_bitacora (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 accion VARCHAR(40) NOT NULL, motivo TEXT NOT NULL, datos JSONB NOT NULL,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
