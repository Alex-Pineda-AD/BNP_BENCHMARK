    MODIFY MONTO_CREDITOS DECIMAL(15,2) NULL,
    ADD CONCEPTO VARCHAR(100) NULL,
    ADD CANTIDAD INT UNSIGNED NULL,
    ADD MONTO DECIMAL(15,2) NULL,
