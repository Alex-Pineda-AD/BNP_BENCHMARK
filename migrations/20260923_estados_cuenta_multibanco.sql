ALTER TABLE resumen_estado_cuenta
    MODIFY CODIGO VARCHAR(20) NULL,
    MODIFY CANTIDAD_DEBITOS INT UNSIGNED NULL,
    MODIFY MONTO_DEBITOS DECIMAL(15,2) NULL,
