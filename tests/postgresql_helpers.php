<?php
// Clone without foreign keys; each identity belongs to the temporary table.
function clonarTablaTemporal(PDO $pdo, string $tabla): void
{
    if (!preg_match('/^[a-z_]+$/D', $tabla)) throw new InvalidArgumentException('Tabla inválida.');
    $columnas = $pdo->prepare('SELECT column_name FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = ? AND column_default LIKE ?');
    $columnas->execute([$tabla, 'nextval(%']);
    $seriales = $columnas->fetchAll(PDO::FETCH_COLUMN);
    $pdo->exec('CREATE TEMPORARY TABLE ' . $tabla . ' (LIKE ' . $tabla . ' INCLUDING ALL)');
    foreach ($seriales as $columna) {
        $nombre = '"' . str_replace('"', '""', $columna) . '"';
        $pdo->exec('ALTER TABLE pg_temp.' . $tabla . ' ALTER COLUMN ' . $nombre . ' DROP DEFAULT');
        $pdo->exec('ALTER TABLE pg_temp.' . $tabla . ' ALTER COLUMN ' . $nombre . ' ADD GENERATED BY DEFAULT AS IDENTITY');
    }
}
