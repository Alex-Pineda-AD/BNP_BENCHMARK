<?php
// Ejecutar por consola: php tests/estado_cuenta_multibanco.php "carpeta de TXT" [--postgres]
// --postgres prueba el guardado en tablas TEMPORALES; no cambia las tablas reales.
if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}
require_once __DIR__ . '/../includes/lectores/bac.php';
require_once __DIR__ . '/../includes/lectores/atlantida.php';
require_once __DIR__ . '/../includes/lectores/ficohsa.php';
require_once __DIR__ . '/../includes/lectores/occidente.php';
require_once __DIR__ . '/../includes/guardar_estado_cuenta.php';

function comprobarEstado(bool $condicion, string $mensaje): void
{
    if (!$condicion) {
        throw new RuntimeException($mensaje);
    }
}

function debeRechazarEstado(callable $accion): void
{
    try {
        $accion();
    } catch (InvalidArgumentException $e) {
        return;
    }
    throw new RuntimeException('Se aceptó un documento inválido.');
}

$carpeta = $argv[1] ?? '';
$lectores = ['BAC' => 'leerBac', 'ATLANTIDA' => 'leerAtlantida',
    'FICOHSA' => 'leerFicohsa', 'OCCIDENTE' => 'leerOccidente'];
$esperados = ['BAC' => 251, 'ATLANTIDA' => 435, 'FICOHSA' => 381, 'OCCIDENTE' => 281];
$textos = [];
$resultados = [];
foreach ($lectores as $banco => $lector) {
    $texto = file_get_contents($carpeta . '/' . $banco . ' ESTADO DE CUENTAS.txt');
    comprobarEstado($texto !== false, 'No se encontró el archivo de ' . $banco);
    $textos[$banco] = $texto;
    $datos = $lector($texto);
    comprobarEstado(count($datos['transacciones']) === $esperados[$banco], 'Cantidad incorrecta: ' . $banco);
    comprobarEstado($datos['cuenta']['MONEDA'] === 'HNL', 'Moneda incorrecta.');
    $resultados[$banco] = $datos;
    foreach ($lectores as $otroBanco => $otroLector) {
        if ($otroBanco !== $banco) {
            debeRechazarEstado(function () use ($otroLector, $texto) { $otroLector($texto); });
        }
    }
}
comprobarEstado($resultados['FICOHSA']['cuenta']['NUMERO_CUENTA'] === '010102347700', 'Se perdieron ceros iniciales.');
comprobarEstado($resultados['FICOHSA']['transacciones'][0]['CREDITO'] === '28572.00', 'CSV con comas leído incorrectamente.');
comprobarEstado($resultados['FICOHSA']['transacciones'][0]['DEBITO'] === '0.00', 'Débito vacío no interpretado.');
comprobarEstado($resultados['ATLANTIDA']['cuenta']['FECHA'] === null, 'Se inventó una fecha de reporte.');
comprobarEstado(count($resultados['OCCIDENTE']['advertencias']) === 0, 'Se advirtió un detalle completo como parcial.');
comprobarEstado($resultados['ATLANTIDA']['resumen'][0]['MONTO_DEBITOS'] === '6412900.00', 'Se perdió el total de débitos.');
comprobarEstado($resultados['ATLANTIDA']['resumen'][0]['MONTO_CREDITOS'] === '4996901.66', 'Se perdió el total de créditos.');
comprobarEstado($resultados['ATLANTIDA']['cuenta']['SALDO_FINAL'] === '1653979.78', 'Se perdió el saldo final.');
comprobarEstado($resultados['ATLANTIDA']['resumen'][0]['CANTIDAD_DEBITOS'] === null, 'Se inventó la cantidad de débitos.');
// Los exportados cortos anteriores no traían fila de totales: siguen siendo válidos.
$sinTotal = preg_replace('/^.*TOTAL MOVIMIENTOS.*\R?/m', '', $textos['ATLANTIDA']);
comprobarEstado(leerAtlantida($sinTotal)['resumen'] === [], 'Se rechazó el formato sin totales.');
// Una transacción sin fecha debe seguir fallando; solo el total está exento.
debeRechazarEstado(function () use ($textos) {
    leerAtlantida(str_replace('1|01/09/26|CR|', '1||CR|', $textos['ATLANTIDA']));
});
comprobarEstado($resultados['OCCIDENTE']['transacciones'][0]['HORA'] === '09:03:07', 'Se perdió la hora.');
debeRechazarEstado(function () { fechaBancaria('31/02/2026', 'd/m/Y'); });
debeRechazarEstado(function () { importeBancario('1,23.00'); });
debeRechazarEstado(function () { importeBancario('10000000000000.00'); });
debeRechazarEstado(function () use ($textos) { leerFicohsa($textos['FICOHSA'] . "\nlinea rota"); });
$duplicado = $resultados['FICOHSA'];
$duplicado['transacciones'][] = $duplicado['transacciones'][0];
comprobarEstado(count(revisarEstadoBancario($duplicado)['advertencias']) === 1, 'No se advirtió el duplicado.');
echo "OK: cuatro formatos, selección incorrecta, CSV, fechas, importes y advertencias.\n";

if (!in_array('--postgres', $argv, true)) {
    exit;
}
require_once __DIR__ . '/../connection/database.php';
$pdo = database();
// PostgreSQL oculta las tablas reales con las temporales de igual nombre SOLO en
// esta conexión. Se eliminan automáticamente al terminar el proceso.
$pdo->exec('CREATE TEMPORARY TABLE estados_cuenta (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ID_USUARIO BIGINT NOT NULL,
    NOMBRE_ARCHIVO VARCHAR(255) NOT NULL, HASH_ARCHIVO CHAR(64) NOT NULL UNIQUE,
    ARCHIVO_ORIGINAL BYTEA NOT NULL, NUMERO_CLIENTE VARCHAR(50) NOT NULL,
    NOMBRE VARCHAR(255) NOT NULL, PRODUCTO VARCHAR(50) NOT NULL, MONEDA VARCHAR(10) NOT NULL,
    SALDO_INICIAL DECIMAL(15,2) NOT NULL, SALDO_LIBROS DECIMAL(15,2) NOT NULL,
    RETENIDOS_DIFERIDOS DECIMAL(15,2) NOT NULL, SALDO_DISPONIBLE DECIMAL(15,2) NOT NULL,
    FECHA DATE NOT NULL, STBGAV DECIMAL(15,2) NOT NULL, STBUNC DECIMAL(15,2) NOT NULL,
    MENSAJE_1 TEXT NOT NULL, MENSAJE_2 TEXT NOT NULL, MENSAJE_3 TEXT NOT NULL,
    MENSAJE_4 TEXT NOT NULL, MENSAJE_5 TEXT NOT NULL, MENSAJE_6 TEXT NOT NULL,
    CREADO_EN TIMESTAMP DEFAULT CURRENT_TIMESTAMP
)');
$pdo->exec('CREATE TEMPORARY TABLE transacciones_estado_cuenta (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ID_ESTADO_CIENTA BIGINT NOT NULL,
    FECHA DATE NOT NULL, REFERENCIA VARCHAR(100) NOT NULL, CODIGO VARCHAR(20) NOT NULL,
    DESCRIPCION TEXT NOT NULL, DEBITO DECIMAL(15,2) NOT NULL,
    CREDITO DECIMAL(15,2) NOT NULL, BALANCE DECIMAL(15,2) NOT NULL
)');
$pdo->exec('CREATE TEMPORARY TABLE resumen_estado_cuenta (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ID_ESTADO_CUENTA BIGINT NOT NULL,
    CODIGO VARCHAR(20) NOT NULL, CANTIDAD_DEBITOS INT NOT NULL,
    MONTO_DEBITOS DECIMAL(15,2) NOT NULL, CANTIDAD_CREDITOS INT NOT NULL,
    MONTO_CREDITOS DECIMAL(15,2) NOT NULL
)');
$sql = file_get_contents(__DIR__ . '/../migrations/postgresql/20260923_estados_cuenta_multibanco.sql');
$sql = preg_replace('/^--.*$/m', '', $sql);
foreach (explode(';', $sql) as $sentencia) {
    if (trim($sentencia) !== '') {
        $pdo->exec($sentencia);
    }
}
foreach ($resultados as $banco => $datos) {
    $id = guardarEstadoCuenta($pdo, 1, 1, $banco . '.txt', $textos[$banco], $datos);
    $consulta = $pdo->prepare('SELECT ARCHIVO_ORIGINAL FROM estados_cuenta WHERE ID = ?');
    $consulta->execute([$id]);
    $archivo = $consulta->fetchColumn();
    if (is_resource($archivo)) $archivo = stream_get_contents($archivo);
    comprobarEstado($archivo === $textos[$banco], 'El archivo original fue modificado.');
    $consulta = $pdo->prepare('SELECT COUNT(*) FROM transacciones_estado_cuenta WHERE ID_ESTADO_CIENTA = ?');
    $consulta->execute([$id]);
    comprobarEstado((int) $consulta->fetchColumn() === $esperados[$banco], 'No se guardaron todos los movimientos.');
}
// La restricción UNIQUE evita cargar nuevamente el mismo archivo.
try {
    guardarEstadoCuenta($pdo, 1, 1, 'duplicado.txt', $textos['BAC'], $resultados['BAC']);
    throw new RuntimeException('Se guardó un archivo duplicado.');
} catch (PDOException $e) {
    comprobarEstado($e->getCode() === '23505', 'Error inesperado al probar el duplicado.');
}
// Forzar un error en el resumen, después de insertar cuenta y movimientos.
$roto = $resultados['BAC'];
$roto['resumen'][0]['CANTIDAD_DEBITOS'] = -1;
$pdo->exec('ALTER TABLE resumen_estado_cuenta ADD CHECK (CANTIDAD_DEBITOS >= 0)');
try {
    guardarEstadoCuenta($pdo, 1, 1, 'fallo.txt', 'original de prueba de rollback', $roto);
    throw new RuntimeException('No falló el resumen inválido.');
} catch (PDOException $e) {
    comprobarEstado(!$pdo->inTransaction(), 'La transacción quedó abierta.');
}
comprobarEstado((int) $pdo->query('SELECT COUNT(*) FROM estados_cuenta')->fetchColumn() === 4, 'Quedó una cuenta parcial.');
comprobarEstado((int) $pdo->query('SELECT COUNT(*) FROM transacciones_estado_cuenta')->fetchColumn() === array_sum($esperados), 'Quedaron movimientos parciales.');
comprobarEstado((int) $pdo->query('SELECT COUNT(*) FROM resumen_estado_cuenta')->fetchColumn() === 10, 'Quedó un resumen parcial.');
echo "OK: migración, inserciones de los cuatro bancos, original intacto, duplicado y rollback en PostgreSQL temporal.\n";
